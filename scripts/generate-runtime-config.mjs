import fs from 'node:fs';
import path from 'node:path';

const originKeys=['CHAMA_CUSTOMER_ORIGIN','CHAMA_MERCHANT_ORIGIN','CHAMA_ADMIN_ORIGIN'];
const portalRoles=new Set(['customer','merchant','admin']);

export function validatePortalOrigin(name,value){
  const raw=String(value??'').trim();
  if(!raw)throw new Error(name+' is required');
  let url;
  try{url=new URL(raw)}catch{throw new Error(name+' must be a valid URL')}
  if(url.protocol!=='https:')throw new Error(name+' must use https');
  if(url.username||url.password||url.search||url.hash)throw new Error(name+' must be a bare origin');
  if(url.pathname!=='/'||url.origin!==raw.replace(/\/$/,''))throw new Error(name+' must not include a path');
  const host=url.hostname.toLowerCase();
  if(host==='github.io'||host.endsWith('.github.io'))throw new Error(name+' cannot use shared github.io origin');
  if(host.includes('*'))throw new Error(name+' cannot contain wildcard');
  if(host==='localhost'||host==='127.0.0.1')throw new Error(name+' production origin cannot be localhost');
  return url.origin;
}

export function validateTurnstileSiteKey(value){
  const key=String(value??'').trim();
  if(!key)throw new Error('CHAMA_TURNSTILE_SITE_KEY is required');
  if(key.length<6||key.length>200||/\s/.test(key))throw new Error('CHAMA_TURNSTILE_SITE_KEY is invalid');
  return key;
}

export function validatePortalRole(value,{required=false}={}){
  const role=String(value??'').trim().toLowerCase();
  if(!role){
    if(required)throw new Error('CHAMA_PORTAL_ROLE is required');
    return '';
  }
  if(!portalRoles.has(role))throw new Error('CHAMA_PORTAL_ROLE must be customer, merchant or admin');
  return role;
}

export function buildRuntimeConfig(env=process.env,{requirePortalRole=false}={}){
  const origins=Object.fromEntries(originKeys.map(k=>[k,validatePortalOrigin(k,env[k])]));
  const unique=new Set(Object.values(origins));
  if(unique.size!==originKeys.length)throw new Error('customer, merchant and admin origins must be distinct');
  const turnstileSiteKey=validateTurnstileSiteKey(env.CHAMA_TURNSTILE_SITE_KEY);
  const portalRole=validatePortalRole(env.CHAMA_PORTAL_ROLE,{required:requirePortalRole});
  return [
    '// Generated by scripts/generate-runtime-config.mjs — public values, not secrets.',
    ...originKeys.map(k=>`globalThis.${k}=${JSON.stringify(origins[k])};`),
    `globalThis.CHAMA_TURNSTILE_SITE_KEY=${JSON.stringify(turnstileSiteKey)};`,
    `globalThis.CHAMA_PORTAL_ROLE=${JSON.stringify(portalRole)};`,
    ''
  ].join('\n');
}

if(import.meta.url===new URL('file://'+process.argv[1]).href){
  const out=process.env.RUNTIME_CONFIG_OUTPUT
    ? path.resolve(process.env.RUNTIME_CONFIG_OUTPUT)
    : path.resolve('js/runtime-config.js');
  fs.mkdirSync(path.dirname(out),{recursive:true});
  fs.writeFileSync(out,buildRuntimeConfig(),'utf8');
  console.log('Runtime config written to '+out);
}
