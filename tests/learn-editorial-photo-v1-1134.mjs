import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const get=p=>new URL('../'+p,import.meta.url);
const js=fs.readFileSync(get('js/learn-premium.js'),'utf8');
const css=fs.readFileSync(get('css/learn-premium.css'),'utf8');
new vm.Script(js,{filename:'js/learn-premium.js'});
const context=vm.createContext({shell:html=>html});
vm.runInContext(js+'\nthis.page=learnPremiumPage',context);
const html=context.page();
assert.match(html,/id="learn-hero-title"/);
assert.match(html,/O essencial para sua casa/);
assert.match(html,/Simples para pedir\. Claro para acompanhar/);
assert.match(html,/class="learn-merchandise"/);
assert.equal((html.match(/class="learn-merchandise-card"/g)||[]).length,4);
for(const item of ['Gás','Água','Carvão','Lenha']) assert(html.includes(item),item+' category missing');
for(const klass of ['learn-photo-gas','learn-photo-water','learn-photo-coal','learn-photo-firewood']) assert(html.includes(klass),klass+' photo missing');
assert.ok(fs.statSync(get('assets/tamao-products-sprite.webp')).size>3000,'real local product imagery must exist');
assert.match(css,/background-image:url\('\.\.\/assets\/tamao-products-sprite\.webp'\)/);
assert.match(css,/background-size:500% 100%/);
assert.match(css,/V1\.1134 — TAMÃO editorial commerce/);
assert.doesNotMatch(html,/learn-essentials-signature-v1133\.svg|learn-delivery-signature-v1133\.svg|learn-cover-visual|learn-confidence-art/);
assert.doesNotMatch(css,/img-src\s+https?:/);
assert.equal((html.match(/class="learn-product-tile"/g)||[]).length,3);
assert.equal((html.match(/data-learn-scene="[1-4]"/g)||[]).length,4);
assert.match(html,/aria-label="Explorar as etapas do pedido"/);
assert.match(html,/onclick="learnPremiumStageAction\(\)"/);
assert.match(html,/COMPROMISSO COM A CLAREZA/);
assert.match(html,/id="learn-faq-search"/);
assert.match(css,/@media\(max-width:700px\)/);
assert.match(css,/@media\(max-width:430px\)/);
assert.match(css,/prefers-reduced-motion:reduce/);
assert.doesNotMatch(html,/mais de \d+ clientes|entrega garantida|5 estrelas|R\$\s?\d+[,\.]\d\d/i);
assert.doesNotMatch(js,/fetch\(|XMLHttpRequest|localStorage|sendBeacon/);
assert.match(css,/font-size:clamp\(37px,3\.45vw,51px\);line-height:1\.045/,'short desktop hero type scale must remain compact');
assert.match(css,/height:clamp\(90px,9\.7vw,130px\)/,'product images must not push purchase CTA below the fold');
assert.match(html,/A revenda confirma o atendimento e informa as etapas/);
console.log('TAMÃO V1.1134 PASS: authentic first-party catalogue imagery, cohesive editorial design, responsive navigation and unchanged commerce');
