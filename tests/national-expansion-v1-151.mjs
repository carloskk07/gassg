import assert from 'node:assert/strict';
import fs from 'node:fs';
const get=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const sql=get('supabase/migrations/20261010120000_national_market_prospects_v1_151.sql');
const capture=get('supabase/functions/capture-prelaunch-lead/index.ts');
const adminOps=get('supabase/functions/admin-ops/index.ts');
const anp=get('supabase/functions/_shared/anp-prospects.js');
const admin=get('js/admin.js');
const acquisition=get('js/acquisition.js');
