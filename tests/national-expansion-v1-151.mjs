const customer=get('js/customer.js');
assert.match(sql,/alter table public.prelaunch_leads[\s\S]+city_ibge_code text/);
for(const table of ['market_cities','market_city_interests','anp_glp_prospects','anp_prospect_refreshes']){
  assert.ok(sql.includes('create table if not exists public.'+table));
  assert.ok(sql.includes('alter table public.'+table+' enable row level security;'));
  assert.ok(sql.includes('revoke all on public.'+table+' from public,anon,authenticated;'));
}
assert.ok(sql.includes('commerce_enabled boolean not null default false'),'cidade nunca nasce vendendo');
assert.ok(!sql.includes('on conflict (state,city_key) do update set commerce_enabled = true'),'cadastro não abre cidade');
assert.match(capture,/resolveLeadCity\(postalCode\)/);
assert.match(capture,/market_cities"\)\.upsert/);
assert.match(capture,/city_ibge_code:resolvedCity\.ibgeCode/);
assert.match(capture,/market_city_interests"\)\.upsert/);
assert.ok(adminOps.includes('admin.from("market_city_interests")'),'demanda por CEP não pode ser contada somente do último cadastro do telefone');
assert.ok(adminAcquisition.includes('d?.marketCityInterests'),'cidades no painel precisam refletir interesses independentes por CEP');
assert.match(capture,/region:resolvedCity\?/);
assert.match(capture,/if\(!postalCode\)return null/);
assert.ok(!capture.includes('POSTAL_CODE_OUTSIDE_SERVICE_AREA'),'captura consentida aceita CEP fora de São Gabriel');
assert.ok(adminOps.includes('"prospect-intelligence"')&&adminOps.includes('requireAdminAction('),'API protegida por sessão');
assert.ok(adminOps.includes('ADMIN_PERMISSION_DENIED')&&adminOps.includes('prospectIntelligence(admin,body.city,body.state'),'RBAC antes da consulta');
assert.ok(anp.includes('https://revendedoresapi.anp.gov.br/v1/glp'),'somente host oficial');
assert.ok(anp.includes('ANP_RESPONSE_FORMAT_UNKNOWN'),'formato desconhecido não é contabilizado como zero');
assert.ok(anp.includes('upsert_anp_prospect_batch'),'reimportação preserva estágio via RPC SQL protegido');
assert.ok(adminOps.includes('sourceStatus:refresh?.status')&&adminOps.includes('warning='),'falha remota explícita');
assert.match(admin,/prospects:new Set\(\['superadmin','readonly','operations','compliance'\]\)/);
assert.ok(admin.includes("adminMenuButton('prospects','Prospectos'"));
assert.ok(admin.includes("adminPanel('prospects',adminProspectsSection(d))"));
assert.ok(adminAcquisition.includes('function adminProspectsSection('));
assert.ok(adminAcquisition.includes('adminProspectSearchCity')&&adminAcquisition.includes('adminLoadProspects'));
assert.ok(!adminAcquisition.includes('Você entrou na nossa lista de abertura em São Gabriel'),'comunicação por cidade');
assert.ok(acquisition.includes('rememberMarketRegion(data.region,postalCode)'),'home consome dado de CEP verificado no backend');
assert.ok(acquisition.includes("if(type!=='customer')return saved==='1'"),'cadastros por CEP não podem ficar bloqueados por envio anterior');
assert.ok(customer.includes('const outsideOriginalMarket='),'mercado fora da região é reconhecido');
assert.ok(customer.includes('!outsideOriginalMarket&&('),'preço de referência São Gabriel não pode ser nacionalizado');
assert.ok(customer.includes('Consultar minha cidade'),'CTA por município precisa consultar ofertas antes do aviso');
